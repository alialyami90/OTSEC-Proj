"""Summarize per-capture engine output into one Markdown table.

For each capture: frames per highest protocol layer according to tshark,
flows per app_proto and alerts per signature from Suricata EVE, and services
plus protocol-specific log line counts from Zeek.
"""
import collections
import json
import os
import sys

OT = ("dnp3", "modbus", "iec60870_104", "mms", "goose", "sv", "enip", "cip", "s7comm")


def tshark_layers(path):
    c = collections.Counter()
    with open(path) as f:
        for line in f:
            layers = line.strip().split(":")
            ot = [p for p in layers if p in OT]
            c[ot[-1] if ot else "non-ot"] += 1
    return c


def suricata(path):
    flows, alerts = collections.Counter(), collections.Counter()
    eve = os.path.join(path, "eve.json")
    if os.path.exists(eve):
        with open(eve) as f:
            for line in f:
                e = json.loads(line)
                if e["event_type"] == "flow":
                    flows[e.get("app_proto", "none")] += 1
                elif e["event_type"] == "alert":
                    alerts[e["alert"]["signature"].replace("OTSEC-EXP ", "")] += 1
    return flows, alerts


def zeek(path):
    services, logs, unknown = collections.Counter(), {}, set()
    for name in sorted(os.listdir(path)):
        if not name.endswith(".log"):
            continue
        with open(os.path.join(path, name)) as f:
            rows = [json.loads(l) for l in f if l.startswith("{")]
        if name == "conn.log":
            for r in rows:
                services[r.get("service", "-")] += 1
        elif name == "unknown_protocols.log":
            unknown = {r["protocol_id"] for r in rows}
        elif name not in ("packet_filter.log",):
            logs[name[:-4]] = len(rows)
    return services, logs, unknown


def fmt(counter):
    return ", ".join(f"{k}={v}" for k, v in sorted(counter.items())) or "-"


def main(work, out):
    names = [l.strip() for l in open(os.path.join(work, "captures.txt")) if l.strip()]
    rows = []
    for n in names:
        d = os.path.join(work, n)
        flows, alerts = suricata(os.path.join(d, "suricata"))
        mflows, malerts = suricata(os.path.join(d, "suricata-midstream"))
        services, logs, unknown = zeek(os.path.join(d, "zeek"))
        rows.append((n, fmt(tshark_layers(os.path.join(d, "tshark-protocols.txt"))),
                     fmt(flows), fmt(alerts), fmt(mflows), fmt(malerts), fmt(services), fmt(logs),
                     ", ".join(sorted(unknown)) or "-"))
    with open(out, "w") as f:
        f.write("# Engine coverage results\n\n")
        f.write("Generated by `run_all.sh`. Versions: see `versions.txt`. Do not edit by hand.\n\n")
        f.write("| Capture | tshark frames by OT layer | Suricata flows by app_proto | Suricata alerts | Suricata midstream flows | Suricata midstream alerts | Zeek conn services | Zeek protocol logs (rows) | Zeek unknown L2/L3 protocols |\n")
        f.write("| --- | --- | --- | --- | --- | --- | --- | --- | --- |\n")
        for r in rows:
            f.write("| " + " | ".join(r) + " |\n")
    print(open(out).read())


if __name__ == "__main__":
    main(sys.argv[1], sys.argv[2])
