"""Send every hostile case through both encoders to a stock rsyslog imtcp
receiver and record what the receiver parsed. Ground truth is the receiver's
own view (rsyslog properties), not this project's code.

Usage: python3 -I run_test.py <work-dir> <results.md>
"""
import base64
import json
import os
import re
import socket
import subprocess
import sys
import time

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from encode import naive_message, octet_frame, profile_message  # noqa: E402
from hostile_cases import CASES  # noqa: E402

CONF = """
global(workDirectory="{work}" maxMessageSize="8k")
module(load="imtcp")
template(name="j" type="list" option.jsonf="on") {{
  property(outname="host" name="hostname" format="jsonf")
  property(outname="msgid" name="msgid" format="jsonf")
  property(outname="sd" name="structured-data" format="jsonf")
  property(outname="msg" name="msg" format="jsonf")
}}
ruleset(name="r") {{ action(type="omfile" file="{out}" template="j") }}
input(type="imtcp" port="{port}" address="127.0.0.1" ruleset="r")
"""


def lines(path):
    if not os.path.exists(path):
        return []
    with open(path) as f:
        return [json.loads(l) for l in f if l.strip()]


def send(port, payload, out, before):
    with socket.create_connection(("127.0.0.1", port)) as s:
        s.sendall(payload)
    deadline, seen = time.time() + 3, -1
    while time.time() < deadline:
        n = len(lines(out))
        if n == seen and n > before:
            break
        seen = n
        time.sleep(0.3)
    return lines(out)[before:]


def sd_param(sd, name):
    m = re.search(name + r'="((?:[^"\\]|\\.)*)"', sd)
    if not m:
        return None
    return re.sub(r'\\(["\\\]])', r"\1", m.group(1))


def recovered(sd):
    text = sd_param(sd, "dtext")
    if text is not None:
        return text.encode()
    b64 = sd_param(sd, "dtext_b64")
    if b64 is not None:
        return base64.b64decode(b64)
    return None


def main(work, results):
    os.makedirs(work, exist_ok=True)
    out, port = os.path.join(work, "received.jsonl"), 10514
    conf = os.path.join(work, "rsyslog.conf")
    with open(conf, "w") as f:
        f.write(CONF.format(work=work, out=out, port=port))
    if os.path.exists(out):
        os.remove(out)
    proc = subprocess.Popen(["rsyslogd", "-n", "-f", conf, "-i", os.path.join(work, "pid")],
                            stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
    time.sleep(1.5)
    rows = []
    try:
        for i, (name, raw) in enumerate(CASES.items()):
            event = {"pri": 134, "received_at": "2026-10-23T15:00:00.123456Z",
                     "collector": "site-a-node1", "msgid": f"C{i:02d}",
                     "event_id": f"0192b7e0-0000-7000-8000-{i:012d}", "origin": "device",
                     "asset_id": "asset:sel751:feeder1", "device_ts_native": "02/28/2007 16:34:28",
                     "precision": "1s", "offset": "unknown",
                     "summary": "SER row", "device_bytes": raw}
            for enc in ("naive", "profile"):
                before = len(lines(out))
                payload = naive_message(event) if enc == "naive" else octet_frame(profile_message(event))
                got = send(port, payload, out, before)
                forged = sum(1 for g in got if g["host"] == "forged-host" or g["msgid"] == "FORGED")
                own = [g for g in got if g["msgid"] == event["msgid"]]
                lossless = "n/a"
                if enc == "profile" and own:
                    rec = recovered(own[0]["sd"])
                    lossless = ("reference-only" if rec is None and "dtext_omitted" in own[0]["sd"]
                                else "yes" if rec == raw else "NO")
                origin = sd_param(own[0]["sd"], "origin") if own and own[0]["sd"] != "-" else "-"
                rows.append((name, enc, len(payload), len(got), forged, origin, lossless))
    finally:
        proc.terminate()
        proc.wait()
    with open(results, "w") as f:
        f.write("# Syslog framing and escaping results\n\n")
        f.write("Generated by `run_test.py` against " +
                subprocess.run(["rsyslogd", "-v"], capture_output=True, text=True).stdout.splitlines()[0].split(" compiled")[0].replace("  ", " ") +
                " (imtcp, maxMessageSize 8k). Do not edit by hand.\n\n")
        f.write("| Case | Encoder | Bytes sent | Messages the receiver parsed | Forged messages | origin param as parsed | Device bytes recovered from SD |\n")
        f.write("| --- | --- | --- | --- | --- | --- | --- |\n")
        for r in rows:
            f.write("| " + " | ".join(str(x) for x in r) + " |\n")
    print(open(results).read())


if __name__ == "__main__":
    main(sys.argv[1], sys.argv[2])
